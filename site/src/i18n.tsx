export const UI_STRINGS: Record<UiLang, typeof EN> = { en: EN, my: MY, si: SI, hi: HI, bn: BN }

export function interpolate(template: string, vars: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (_, key) => String(vars[key] ?? ''))
}

export function formatUiDate(iso: string, lang: UiLang, month: 'short' | 'long' = 'long') {
  const [y, m, d] = iso.split('-').map(Number)
  return new Date(y, m - 1, d).toLocaleDateString(DATE_LOCALE[lang] || 'en-GB', {
    day: 'numeric',
    month,
    year: 'numeric',
  })
}

export function readUiLang(): UiLang {
  try {
    const value = localStorage.getItem(STORAGE_KEY)
    if (value === 'en' || value === 'my' || value === 'si' || value === 'hi' || value === 'bn') return value
  } catch { /* ignore */ }
  return 'en'
}

type Ctx = {
  uiLang: UiLang
  setUiLang: (lang: UiLang) => void
  t: typeof EN
}

const UiLangContext = createContext<Ctx>({
  uiLang: 'en',
  setUiLang: () => {},
  t: EN,
})

export function UiLangProvider({ children }: { children: ReactNode }) {
  const [uiLang, setUiLangState] = useState<UiLang>(readUiLang)

  useEffect(() => {
    document.documentElement.lang = uiLang
    document.documentElement.setAttribute('data-ui-lang', uiLang)
  }, [uiLang])

  const value = useMemo<Ctx>(() => ({
    uiLang,
    setUiLang(next) {
      try { localStorage.setItem(STORAGE_KEY, next) } catch { /* ignore */ }
      setUiLangState(next)
    },
        t: UI_STRINGS[uiLang] || EN,
  }), [uiLang])

  return <UiLangContext.Provider value={value}>{children}</UiLangContext.Provider>
}

export function useUi() {
  return useContext(UiLangContext)
}
